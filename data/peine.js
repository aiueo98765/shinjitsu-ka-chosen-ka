/* ══════════════════════════════════════════════════════
   peine.js ─ 罰の札
   逃げた者が引く。断れない。
   n がついた札は「縛り」で、その巡数だけ効き続ける。
   n がない札はその場かぎり。
   f がついた札は「逃げた者にしか意味が通らない」札。
   卓の頭から罰を引き当てたときには出てこない。
   ══════════════════════════════════════════════════════ */

